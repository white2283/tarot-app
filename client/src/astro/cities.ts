/** 容错查找城市:支持"北京市/张家口市"等带后缀写法 */
export function findCity(name: string): City | undefined {
  if (!name) return undefined;
  const n = name.trim();
  if (!n) return undefined;
  const exact = CITIES.find(c => c.name === n);
  if (exact) return exact;
  // 末尾带 市/县/区/盟 时尝试去掉后缀
  const stripped = n.replace(/[市县区盟]$/, "");
  if (stripped !== n) {
    const hit = CITIES.find(c => c.name === stripped);
    if (hit) return hit;
  }
  // 缺"市"时尝试补上
  const added = CITIES.find(c => c.name === n + "市");
  if (added) return added;
  return undefined;
}
